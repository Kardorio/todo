local store = require("scripts.storage")
local tasks = require("scripts.task_manager")
local location = require("scripts.location_manager")

return function(player)
  local original = storage.todo_manager
  storage.todo_manager = {schema_version = 1, next_id = 1, tasks = {
    [7] = {id = 7, title = "Legacy", description = "Notes", status = "TODO", created_by = 1,
      creator_name = "Fixture", created_at = 12, position = {x = 5, y = -8}, surface_index = 1}
  }, players = {[1] = {panel_visible = false, panel_location = {x = 10, y = 20}}}}
  local migrated = store.initialize()
  assert(migrated.schema_version == 2 and migrated.next_id == 8)
  assert(migrated.tasks[7].priority == 0 and migrated.tasks[7].order == 7)
  assert(migrated.tasks[7].revision == 1 and migrated.tasks[7].description == "Notes")
  assert(migrated.players[1].pinned and migrated.players[1].collapsed)
  assert(migrated.players[1].panel_visible == false)
  assert(migrated.players[1].panel_location.x == 10)
  assert(store.initialize() == migrated and migrated.tasks[7].revision == 1)
  storage.todo_manager = nil
  store.initialize()
  local prefs = store.player(player.index)
  assert(prefs.panel_visible and next(prefs.pinned) == nil and next(prefs.collapsed) == nil)
  local parent = assert(tasks.create("Root", player, game.tick, nil, false))
  assert(not parent.position and not parent.surface_index)
  assert(tasks.create(" ", player, game.tick) == nil)
  local invalid, reason = tasks.create("No parent", player, game.tick, -1)
  assert(not invalid and reason == "invalid_parent")
  local first = assert(tasks.create("First", player, game.tick, parent.id, false))
  local second = assert(tasks.create("Second", player, game.tick, parent.id, false))
  local ignored = assert(tasks.create("Ignored", player, game.tick, parent.id, false))
  assert(tasks.update(first.id, {status = "DONE"}))
  assert(tasks.update(ignored.id, {status = "IGNORED"}))
  local done, total = tasks.progress(parent.id)
  assert(done == 1 and total == 2 and parent.status == "TODO")
  assert(tasks.update(second.id, {status = "DONE"}))
  done, total = tasks.progress(parent.id)
  assert(done == total and parent.status == "TODO")
  assert(tasks.update(second.id, {status = "TODO"}))
  assert(tasks.has_children(parent.id) and not tasks.has_children(first.id))
  assert(tasks.move(second.id, -1))
  assert(tasks.children(parent.id)[1].id == second.id)
  assert(tasks.move(second.id, -1))
  assert(tasks.children(parent.id)[1].id == second.id)
  assert(tasks.move(second.id, 1))
  assert(tasks.children(parent.id)[1].id == first.id)
  invalid, reason = tasks.move(second.id, 0)
  assert(not invalid and reason == "invalid_direction")
  assert(not tasks.can_parent(parent.id, second.id))
  assert(not tasks.can_parent(parent.id, parent.id))
  assert(tasks.can_parent(second.id, false))
  local revision = parent.revision
  invalid, reason = tasks.update(parent.id, {parent_id = first.id}, revision)
  assert(not invalid and reason == "cycle" and parent.revision == revision)
  invalid, reason = tasks.update(parent.id, {parent_id = 987654321}, revision)
  assert(not invalid and reason == "invalid_parent")
  invalid, reason = tasks.update(parent.id, {status = "UNKNOWN"}, revision)
  assert(not invalid and reason == "invalid_status")
  invalid, reason = tasks.update(parent.id, {priority = 4}, revision)
  assert(not invalid and reason == "invalid_priority")
  invalid, reason = tasks.update(parent.id, {title = "  "}, revision)
  assert(not invalid and reason == "title_required")
  assert(tasks.update(parent.id, {title = "  Renamed  ", description = "Notes", priority = 3}, revision))
  invalid, reason = tasks.update(parent.id, {title = "Lost update"}, revision)
  assert(not invalid and reason == "conflict" and parent.title == "Renamed")
  assert(parent.description == "Notes" and parent.priority == 3)
  local capture = location.capture(player)
  assert(tasks.update(parent.id, capture))
  capture.position.x = capture.position.x + 100
  assert(parent.position.x ~= capture.position.x)
  invalid, reason = tasks.update(parent.id, {position = {x = math.huge, y = 0}})
  assert(not invalid and reason == "invalid_location")
  invalid, reason = tasks.update(parent.id, {surface_index = -2})
  assert(not invalid and reason == "invalid_location")
  assert(tasks.update(parent.id, {position = false, surface_index = false}))
  assert(not parent.position and not parent.surface_index)
  assert(location.describe(parent)[1] == "todo.no-location")
  local navigated, navigation_error = location.navigate(player, parent)
  assert(not navigated and navigation_error == "no_location")
  assert(tasks.update(parent.id, {position = {x = 1, y = 2}, surface_index = 987654321}))
  assert(location.describe(parent)[2][1] == "todo.missing-surface")
  navigated, navigation_error = location.navigate(player, parent)
  assert(not navigated and navigation_error == "missing_surface")
  assert(tasks.update(second.id, {parent_id = false}))
  assert(second.parent_id == nil)
  assert(tasks.update(second.id, {parent_id = parent.id}))
  local grandchild = assert(tasks.create("Grandchild", player, game.tick, first.id, false))
  local entries = tasks.tree({[parent.id] = true})
  assert(#entries == 1 and entries[1].task.id == parent.id)
  entries = tasks.tree({}, {grandchild.id, first.id, parent.id, parent.id})
  assert(#entries == 5 and entries[1].depth == 0)
  entries = tasks.tree({}, {grandchild.id})
  assert(#entries == 1 and entries[1].depth == 0)
  prefs.pinned[first.id], prefs.collapsed[first.id], prefs.selected_id = true, true, first.id
  local other_prefs = store.player(player.index + 10000)
  other_prefs.pinned[first.id], other_prefs.collapsed[first.id], other_prefs.selected_id = true, true, first.id
  assert(tasks.delete(first.id))
  assert(grandchild.parent_id == parent.id)
  assert(not prefs.pinned[first.id] and not prefs.collapsed[first.id] and not prefs.selected_id)
  assert(not other_prefs.pinned[first.id] and not other_prefs.collapsed[first.id] and not other_prefs.selected_id)
  assert(tasks.children(parent.id)[1].id == grandchild.id)
  invalid, reason = tasks.update(first.id, {title = "Deleted"})
  assert(not invalid and reason == "missing")
  invalid, reason = tasks.delete(first.id)
  assert(not invalid and reason == "missing")
  local chain_root = assert(tasks.create("Deep root", player, game.tick, nil, false))
  local tip = chain_root
  local first_deep_child
  for depth = 1, 1500 do
    tip = assert(tasks.create("Depth " .. depth, player, game.tick, tip.id, false))
    if depth == 1 then first_deep_child = tip end
  end
  entries = tasks.tree({}, {chain_root.id})
  assert(#entries == 1501 and entries[1501].depth == 1500)
  assert(not tasks.can_parent(chain_root.id, tip.id))
  invalid, reason = tasks.update(chain_root.id, {parent_id = tip.id})
  assert(not invalid and reason == "cycle")
  entries = tasks.tree({[chain_root.id] = true}, {chain_root.id})
  assert(#entries == 1)
  assert(tasks.delete(chain_root.id))
  assert(first_deep_child.parent_id == nil)
  assert(tasks.tree({}, {tip.id})[1].task.id == tip.id)
  storage.todo_manager = original
  log("TODO_MODEL_OK")
end
